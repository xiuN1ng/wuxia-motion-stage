import * as THREE from 'three';
import { BONE_IDX } from '../rig/HumanoidRig.js';
import {
  createNeutralKeyframe,
  setBoneLocalEulerDeg,
  snapKeyframeFeetToFloor,
} from './KeyframeInbetweener.js';

function buildSculptedKeyframe({
  id,
  label,
  durationToNext = 0.38,
  holdSec = 0,
  spinTurns = 0,
  easing = 'wuxia_snap',
  rootPos = [0, 0.94, 0],
  snapFloor = true,
  floorY = 0.08,
  angles = {},
}) {
  const kf = createNeutralKeyframe({
    id,
    label,
    durationToNext,
    holdSec,
    spinTurns,
    easing,
    rootPos: new THREE.Vector3(rootPos[0], rootPos[1], rootPos[2]),
  });

  for (const [boneName, xyz] of Object.entries(angles)) {
    const idx = BONE_IDX[boneName];
    if (idx !== undefined && Array.isArray(xyz)) {
      setBoneLocalEulerDeg(kf, idx, xyz[0] || 0, xyz[1] || 0, xyz[2] || 0);
    }
  }

  if (snapFloor) {
    snapKeyframeFeetToFloor(kf, floorY);
  }
  return kf;
}

